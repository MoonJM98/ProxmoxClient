#!/usr/bin/env python3
"""글자 폭 표(CharWidthTable.g.cs) 만들기 — 유니코드 16 UCD 파일에서.

쓰는 법:
  curl -O https://www.unicode.org/Public/16.0.0/ucd/EastAsianWidth.txt
  curl -O https://www.unicode.org/Public/16.0.0/ucd/emoji/emoji-data.txt
  curl -O https://www.unicode.org/Public/16.0.0/ucd/extracted/DerivedGeneralCategory.txt
  python3 -I gen_width.py <UCD 폴더> > ProxmoxClient.UI/Views/Terminal/CharWidthTable.g.cs

규칙(glibc wcwidth 와 같게):
  - 기본 1. 애매한 폭(A)도 1.
  - East_Asian_Width W·F → 2. 빈 CJK 자리(3400..4DBF 등)도 2.
  - Emoji_Presentation=Yes → 2. 단 지역 표시 문자(국기 글자 1F1E6..1F1FF)는 1 — 두 개가 짝이면 해석기가 두 칸 한 묶음으로 만든다.
  - 일반 범주 Mn·Me·Cf → 0 (U+00AD 소프트 하이픈은 1).
  - 한글 중성·종성 자모(1160..11FF, D7B0..D7FF) → 0 — 앞 초성에 붙는다.
"""
import os
import sys

MAX = 0x110000


def ranges(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cps, value = [p.strip() for p in line.split(";")[:2]]
            a, _, b = cps.partition("..")
            yield int(a, 16), int(b or a, 16), value


def main(folder):
    width = bytearray([1]) * MAX

    def fill(a, b, w):
        width[a:b + 1] = bytes([w]) * (b - a + 1)

    # 빈 CJK 자리 — 파일 머리말이 W 로 보라고 한다
    for a, b in [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]:
        fill(a, b, 2)
    for a, b, v in ranges(os.path.join(folder, "EastAsianWidth.txt")):
        if v in ("W", "F"):
            fill(a, b, 2)
    for a, b, v in ranges(os.path.join(folder, "emoji-data.txt")):
        if v == "Emoji_Presentation":
            fill(a, b, 2)
    fill(0x1F1E6, 0x1F1FF, 1)
    for a, b, v in ranges(os.path.join(folder, "DerivedGeneralCategory.txt")):
        if v in ("Mn", "Me", "Cf"):
            fill(a, b, 0)
    fill(0x1160, 0x11FF, 0)
    fill(0xD7B0, 0xD7FF, 0)
    width[0xAD] = 1

    out = {0: [], 2: []}
    start = 0
    for cp in range(MAX + 1):
        w = width[cp] if cp < MAX else 1
        prev = width[cp - 1] if cp > 0 else 1
        if w == prev:
            continue
        if prev != 1:
            out[prev].append((start, cp - 1))
        start = cp

    def table(name, items):
        lines = []
        row = []
        for a, b in items:
            row.append(f"0x{a:X}, 0x{b:X},")
            if len(row) == 6:
                lines.append("        " + " ".join(row))
                row = []
        if row:
            lines.append("        " + " ".join(row))
        return f"    internal static readonly int[] {name} =\n    [\n" + "\n".join(lines) + "\n    ];\n"

    sys.stdout.write(
        "// <auto-generated> tools/TerminalTests/gen_width.py 로 만든 파일 — 손으로 고치지 않는다(유니코드 16). </auto-generated>\n"
        "namespace ProxmoxClient.UI.Views.Terminal;\n\n"
        "/// <summary>글자 폭 범위 — [시작, 끝] 쌍이 차례로. 이진 탐색으로 찾는다.</summary>\n"
        "internal static class CharWidthTable\n{\n"
        "    /// <summary>폭 0 (결합 문자·서식 문자·한글 중성/종성 자모).</summary>\n"
        + table("Zero", out[0]) +
        "\n    /// <summary>폭 2 (동아시아 넓은 글자·그림 문자).</summary>\n"
        + table("Wide", out[2]) +
        "}\n")
    sys.stderr.write(f"zero {len(out[0])} wide {len(out[2])}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
